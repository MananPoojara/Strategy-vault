import { apiJson } from "./api";

/* Research page ("Claude's work"): the jay branch's commit timeline, read from data/research-work.json.
   That file is generated by Context/guru/webapp/scripts/build_research_work.py from read-only git history
   and served from the frontend-data mount; nothing here talks to a database or the auth service. */

export const DATA_URL = "data/research-work.json";
export const BUILD_HINT = "Run python3 Context/guru/webapp/scripts/build_research_work.py to build data/research-work.json.";

export interface WorkEvent {
  key: string; short: string; at: string; label: string; who: string; work: string;
  /** Co-authors from the commit's Co-Authored-By lines, e.g. "Claude Opus 5.5". */
  with: string[];
  files: number; insertions: number; deletions: number; merge: boolean;
  /** YT strategy ids new in this commit, and ids that disappeared. */
  added: string[]; removed: string[];
  /** YT strategy ids in the tree after this commit. */
  count: number;
}
export interface WorkDay { date: string; commits: number; added: number; removed: number; count: number; authors: string[] }
export interface ResearchWork {
  version: number; generated_at: string; branch: string; head: string;
  uncommitted: { files: number; note: string };
  method: string;
  totals: { commits: number; days: number; strategies: number; added: number; authors: string[] };
  days: WorkDay[];
  events: WorkEvent[];
}
export type WorkLoad = { ok: true; data: ResearchWork } | { ok: false; problem: string };

/** Loads the timeline; a missing, unreadable or wrongly shaped file gives a notice instead of an exception. */
export async function loadResearchWork(fetchImpl: typeof fetch = fetch): Promise<WorkLoad> {
  let body: unknown;
  try {
    const r = await fetchImpl(DATA_URL, { cache: "no-store", credentials: "same-origin" });
    if (!r.ok) return { ok: false, problem: `The timeline file is not available (${r.status}). ${BUILD_HINT}` };
    body = await r.json();
  } catch {
    return { ok: false, problem: `The timeline file could not be read. ${BUILD_HINT}` };
  }
  return checkWork(body);
}

export function checkWork(body: unknown): WorkLoad {
  const d = body as Partial<ResearchWork> | null;
  const okEvent = (e: Partial<WorkEvent>) => e && typeof e.key === "string" && typeof e.at === "string" && !Number.isNaN(Date.parse(e.at))
    && typeof e.label === "string" && Array.isArray(e.added) && typeof e.count === "number";
  if (!d || typeof d !== "object" || !Array.isArray(d.events) || !Array.isArray(d.days) || !d.totals || !d.events.every(okEvent))
    return { ok: false, problem: `The timeline file is not in the expected format. ${BUILD_HINT}` };
  const events = d.events.map(e => ({ ...e, who: e.who || "", work: e.work || "", with: e.with || [], removed: e.removed || [], short: e.short || e.key.slice(0, 8) }));
  return { ok: true, data: { ...(d as ResearchWork), uncommitted: d.uncommitted || { files: 0, note: "" }, events } };
}

const IST: Intl.DateTimeFormatOptions = { timeZone: "Asia/Kolkata" };
/** Calendar day in India time (YYYY-MM-DD), the same day the generator uses. */
export const dayKey = (iso: string) => new Date(iso).toLocaleDateString("en-CA", IST);
export const fmtDay = (day: string) => new Date(`${day}T12:00:00+05:30`).toLocaleDateString("en-IN", { ...IST, weekday: "short", day: "numeric", month: "short", year: "numeric" });
export const fmtTime = (iso: string) => new Date(iso).toLocaleTimeString("en-IN", { ...IST, hour: "2-digit", minute: "2-digit", hour12: false });
export const fmtStamp = (iso: string) => `${fmtDay(dayKey(iso))}, ${fmtTime(iso)}`;
export const num = (n: number | undefined) => (n ?? 0).toLocaleString("en-IN");

/** Events grouped by India-time day, newest day first and newest event first within a day. */
export function groupByDay(events: WorkEvent[]): { day: string; items: WorkEvent[] }[] {
  const sorted = [...events].sort((a, b) => Date.parse(b.at) - Date.parse(a.at));
  const days = new Map<string, WorkEvent[]>();
  for (const e of sorted) { const k = dayKey(e.at); days.set(k, [...(days.get(k) || []), e]); }
  return [...days].map(([day, items]) => ({ day, items }));
}

/** Every strategy id with the commit that first added it, newest first. */
export function strategiesAdded(events: WorkEvent[]): { id: string; event: WorkEvent }[] {
  const out: { id: string; event: WorkEvent }[] = [];
  for (const e of [...events].sort((a, b) => Date.parse(b.at) - Date.parse(a.at))) for (const id of e.added) out.push({ id, event: e });
  return out;
}

/** The co-author kind for colouring: "claude", "codex" or "" (a person alone). */
export const helperKind = (e: Pick<WorkEvent, "with">) => e.with.some(w => /claude/i.test(w)) ? "claude" : e.with.some(w => /codex/i.test(w)) ? "codex" : "";

/** YT strategy names from the engine catalogue (id → name); an empty map if it cannot be loaded. */
export async function ytNames(): Promise<Record<string, string>> {
  try {
    const d = await apiJson<{ id: string; name: string }[] | { strategies: { id: string; name: string }[] }>("/api/in/guru/yt/strategies");
    const list = Array.isArray(d) ? d : d.strategies || [];
    return Object.fromEntries(list.filter(s => s && s.id).map(s => [s.id, s.name || s.id]));
  } catch {
    return {};
  }
}

/** The view lives in the hash (#/research?v=strategies) so links can be shared. */
export const PATH = "/research";
export type View = "claude" | "strategies" | "tradesheets";
export function readView(hash = location.hash): View {
  const v = new URLSearchParams(hash.split("?")[1] || "").get("v");
  return v === "strategies" || v === "tradesheets" ? v : "claude";
}
export const viewHref = (v: View) => `#${PATH}${v === "claude" ? "" : `?v=${v}`}`;
