fn ema(v: &[f64], n: usize) -> Vec<f64> {
    let a = 2. / (n as f64 + 1.);
    let mut out = Vec::with_capacity(v.len());
    for (i, &x) in v.iter().enumerate() { out.push(if i == 0 { x } else { out[i - 1] + a * (x - out[i - 1]) }); }
    out
}

/// +1 / -1 / 0 per bar: the weekly FIRMROC MACD direction of the last week completed before the bar's week
fn direction(x: &Ctx) -> Vec<f64> {
    let n = x.r.len();
    let wk: Vec<i64> = x.r.iter().map(|r| { let d = day_num(&r.date); d - (weekday(d) + 6).rem_euclid(7) }).collect(); // Monday of the week
    let ends: Vec<usize> = (0..n).filter(|&k| k + 1 == n || wk[k + 1] != wk[k]).collect();
    // the 55-day FIRMROC (p.72) read at each week's last close
    let w0 = ends.iter().position(|&k| k >= 55).unwrap_or(ends.len());
    let f: Vec<f64> = ends[w0..].iter().map(|&k| (x.c[k] - x.c[k - 55]) / x.c[k] * 100. * 365. / 91.).collect();
    let mut dir_w = vec![0.; ends.len()];
    if !f.is_empty() {
        let (e12, e26) = (ema(&f, 12), ema(&f, 26));
        let macd: Vec<f64> = e12.iter().zip(&e26).map(|(a, b)| a - b).collect();
        let sig = ema(&macd, 9);
        for j in 0..f.len() { dir_w[j + w0] = if macd[j] > sig[j] { 1. } else if macd[j] < sig[j] { -1. } else { 0. }; }
    }
    let mut out = vec![0.; n];
    let mut w = 0usize; // index into ends of the first week not yet complete before bar k
    for k in 0..n {
        while w < ends.len() && wk[ends[w]] < wk[k] { w += 1; }
        out[k] = if w > 0 { dir_w[w - 1] } else { 0. };
    }
    out
}

pub fn run(id: &str, x: &Ctx, from: usize, to: usize, p: &Params) -> Option<Vec<Trade>> {
    if id != "wsspec_serial_13ema" { return None; }
    let n = x.r.len();
    if n == 0 || from > to || to >= n { return Some(vec![]); }
    let filt = p.get("filter").copied().unwrap_or(0.) >= 0.5;
    let (eh, el) = (ema(&x.h, 13), ema(&x.l, 13));
    let dir = if filt { direction(x) } else { vec![1.; n] };
    let mut out = vec![];
    let mut cur: Option<Trade> = None;
    for t in from.max(1)..=to {
        if let Some(q) = cur.as_ref() {
            if t > q.legs[0].i {
                let (hit, px) = if q.dir > 0. { (x.l[t] <= el[t - 1], x.o[t].min(el[t - 1])) } else { (x.h[t] >= eh[t - 1], x.o[t].max(eh[t - 1])) };
                if hit {
                    let mut q = cur.take().unwrap();
                    (q.exit_i, q.exit_px, q.signal_i, q.reason) = (t, px, t, "through the 13-day EMA on the other side".into());
                    out.push(q);
                    continue; // no new entry on the exit day
                }
            }
            continue;
        }
        let d = dir[t];
        let fill = if d > 0. && x.h[t] >= eh[t - 1] { Some(x.o[t].max(eh[t - 1])) } else if d < 0. && x.l[t] <= el[t - 1] { Some(x.o[t].min(el[t - 1])) } else { None };
        if let Some(px) = fill {
            cur = Some(Trade { dir: d, legs: vec![Leg { i: t, px, w: 1. }], exit_i: t, exit_px: f64::NAN, reason: String::new(), entry_kind: "stop", signal_i: t, open: false, exits: vec![] });
        }
    }
    if let Some(mut q) = cur { (q.exit_i, q.exit_px, q.signal_i, q.open, q.reason) = (to, x.c[to], to, true, "open".into()); out.push(q); }
    Some(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::Row;
    #[test]
    fn buys_through_the_ema_of_highs_and_exits_through_the_ema_of_lows() {
        let mk = |d: usize, o: f64, h: f64, l: f64, c: f64| Row { ticker: "T".into(), date: format!("2020-01-{:02}", d + 1), open: o, high: h, low: l, close: c, volume: None };
        let v = vec![mk(0, 10., 11., 9., 10.), mk(1, 10., 11., 9., 10.), mk(2, 10.5, 12., 10., 11.5), mk(3, 11.5, 12., 11., 11.), mk(4, 8., 8.5, 7., 8.)];
        let x = Ctx::new(&v, &v, &[]);
        // default (long only): day 1 high 11 >= EMA13(high) of day 0 = 11 -> long at max(open 10, 11) = 11; day 4 opens 8 below EMA13(low) of day 3
        let t = run("wsspec_serial_13ema", &x, 0, 4, &Params::new()).unwrap();
        let el3 = { let e = ema(&x.l, 13); e[3] };
        assert!(el3 > 8.);
        assert_eq!(t.iter().map(|t| (t.dir, t.legs[0].i, t.legs[0].px, t.exit_i, t.exit_px)).collect::<Vec<_>>(), vec![(1., 1, 11., 4, 8.)]);
        assert_eq!(direction(&x), vec![0.; 5]); // fewer than 56 weekly closes: no direction
        assert!(crate::gate::get("wsspec_serial_13ema").is_some());
    }
}
