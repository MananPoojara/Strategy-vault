pub fn params(id: &str) -> Option<Vec<ParamDef>> {
    let r = T.iter().find(|r| r.0 == id)?;
    let p = |key, label, def, min, max, step| ParamDef { key, label, def, min, max, step };
    let mut v = vec![];
    if r.2 != Fam::Trb { v.push(p("short_ma", "Short moving average, days", r.3, 1., 20., 1.)); }
    v.push(p("long_ma", if r.2 == Fam::Trb { "Range (local max/min), preceding days" } else { "Long moving average, days" }, r.4, 10., 300., 10.));
    v.push(p("band_pct", "Band, %", r.5 * 100., 0., 5., 0.5));
    if r.2 != Fam::Vma { v.push(p("hold", "Holding period, days", 10., 5., 20., 1.)); }
    v.push(p("sell_short", "Sell signal: 1 = go short, 0 = move out of the market", 1., 0., 1., 1.));
    Some(v)
}

fn entry(dir: f64, i: usize, px: f64) -> Trade {
    Trade { dir, legs: vec![Leg { i, px, w: 1. }], exit_i: i, exit_px: px, reason: String::new(), entry_kind: "close", signal_i: i, open: false, exits: vec![] }
}
fn finish(mut out: Vec<Trade>, cur: Option<Trade>, x: &Ctx, to: usize) -> Vec<Trade> {
    if let Some(mut t) = cur { t.exit_i = to; t.exit_px = x.c[to]; t.signal_i = to; t.reason = "open".into(); t.open = true; out.push(t); }
    out
}
/// Strict a > b as the paper states it, decided so that values equal in exact arithmetic (e.g. a close exactly 1% above
/// its average, missed by float rounding) are equal, not greater (review 25 Oct 2026).
fn gt(a: f64, b: f64) -> bool { a - b > 1e-12 * a.abs().max(b.abs()) }
fn ma(c: &[f64], n: usize, i: usize) -> f64 { c[i + 1 - n..=i].iter().sum::<f64>() / n as f64 }

pub fn run(id: &str, x: &Ctx, from: usize, to: usize, p: &Params) -> Option<Vec<Trade>> {
    let r = T.iter().find(|r| r.0 == id)?;
    let schema = params(id)?;
    if from > to || to >= x.c.len() { return None; }
    let g = |k: &str| p.get(k).copied().unwrap_or_else(|| schema.iter().find(|d| d.key == k).map_or(0., |d| d.def));
    let (s, l, b, hold) = (g("short_ma").max(1.) as usize, g("long_ma").max(1.) as usize, g("band_pct") / 100., g("hold").max(1.) as usize);
    let short = g("sell_short") >= 0.5;
    let c = &x.c;
    let side = |d: f64| if d < 0. && !short { 0. } else { d };
    let (mut out, mut cur): (Vec<Trade>, Option<Trade>) = (vec![], None);
    match r.2 {
        Fam::Vma => {
            for i in from..=to {
                if i + 1 < l.max(s) { continue; }
                let (sv, lv) = (ma(c, s, i), ma(c, l, i));
                let d = side(if gt(sv, lv * (1. + b)) { 1. } else if gt(lv * (1. - b), sv) { -1. } else { 0. });
                if cur.as_ref().map_or(0., |t| t.dir) == d { continue; }
                if let Some(mut t) = cur.take() { t.exit_i = i; t.exit_px = c[i]; t.signal_i = i; t.reason = "Signal changed · close".into(); out.push(t); }
                if d != 0. && i < to { cur = Some(entry(d, i, c[i])); }
            }
        }
        Fam::Fma | Fam::Trb => {
            let mut next_ok = from; // signals on the `hold` days after a signal are ignored
            for i in from..=to {
                if let Some(t) = cur.as_ref() {
                    if i == t.signal_i + hold {
                        let mut t = cur.take().unwrap(); t.exit_i = i; t.exit_px = c[i]; t.reason = format!("{hold}-day holding period · close"); t.signal_i = i; out.push(t);
                    }
                }
                if i < next_ok { continue; }
                let sig = if r.2 == Fam::Fma {
                    if i < l.max(s) { continue; }
                    let (s0, l0, s1, l1) = (ma(c, s, i), ma(c, l, i), ma(c, s, i - 1), ma(c, l, i - 1));
                    if gt(s0, l0 * (1. + b)) && gt(l1 * (1. + b), s1) { 1. } else if gt(l0 * (1. - b), s0) && gt(s1, l1 * (1. - b)) { -1. } else { 0. }
                } else {
                    if i < l { continue; }
                    let w = &c[i - l..i];
                    let (hi, lo) = (w.iter().copied().fold(f64::MIN, f64::max), w.iter().copied().fold(f64::MAX, f64::min));
                    if gt(c[i], hi * (1. + b)) { 1. } else if gt(lo * (1. - b), c[i]) { -1. } else { 0. }
                };
                if sig == 0. { continue; }
                next_ok = i + hold + 1;
                let d = side(sig);
                if d != 0. && i < to { let mut t = entry(d, i, c[i]); t.signal_i = i; cur = Some(t); }
            }
        }
    }
    Some(finish(out, cur, x, to))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::Row;
    fn ctx_rows(cl: &[f64]) -> Vec<Row> {
        cl.iter().enumerate().map(|(i, &c)| Row { ticker: "T".into(), date: format!("{:04}-01-01", 2000 + i), open: c, high: c, low: c, close: c, volume: None }).collect()
    }
    #[test]
    fn trb_holds_ten_days_and_blocks_signals() {
        // 50 flat days at 100, then a steady climb: every climbing day is a new 50-day high.
        let mut cl = vec![100.; 50];
        cl.extend((1..=30).map(|k| 100. + k as f64));
        let r = ctx_rows(&cl); let x = Ctx::new(&r, &r, &[]);
        let ts = run("bllstr_trb_50_0", &x, 0, 79, &Params::new()).unwrap();
        assert_eq!(ts[0].legs[0].i, 50); assert_eq!(ts[0].exit_i, 60); assert_eq!(ts[0].dir, 1.);
        assert_eq!(ts[1].legs[0].i, 61); // day 60 signal is inside the blocked ten days
        assert_eq!(ts[2].legs[0].i, 72); assert!(ts[2].open);
    }
    #[test]
    fn vma_band_is_flat_and_sell_reverses() {
        let mut cl = vec![100.; 60]; cl.extend([102., 100.5, 98., 97.]);
        let r = ctx_rows(&cl); let x = Ctx::new(&r, &r, &[]);
        let ts = run("bllstr_vma_1_50_1", &x, 49, 63, &Params::new()).unwrap();
        assert_eq!(ts.len(), 2); assert_eq!((ts[0].legs[0].i, ts[0].exit_i), (60, 61)); assert_eq!(ts[1].dir, -1.); assert_eq!(ts[1].legs[0].i, 62);
        let lo = run("bllstr_vma_1_50_1", &x, 49, 63, &Params::from([("sell_short".into(), 0.)])).unwrap();
        assert_eq!(lo.len(), 1);
    }
}
