pub fn params(id: &str) -> Option<Vec<ParamDef>> {
    let p = |key, label, def, min, max, step| ParamDef { key, label, def, min, max, step };
    (id == "gmtot_trend").then(|| vec![p("fast", "Short exponential average (7 = half the DJIA's 14-15-day cycle)", 7., 2., 50., 1.),
        p("slow", "Long exponential average (42 = six times the short)", 42., 5., 300., 1.),
        p("sig", "Signal simple average of the oscillator (21 = three times the short)", 21., 2., 150., 1.),
        p("side", "1 = long only (default 0: long and short)", 0., 0., 1., 1.)])
}

pub fn run(id: &str, x: &Ctx, from: usize, to: usize, p: &Params) -> Option<Vec<Trade>> {
    if !reviewed(id) || from >= to || to >= x.r.len() { return None; }
    let schema = params(id)?;
    let g = |k: &str| p.get(k).copied().unwrap_or_else(|| schema.iter().find(|d| d.key == k).map_or(f64::NAN, |d| d.def)).round().max(1.) as usize;
    let (f, s) = (ema(&x.c, g("fast")), ema(&x.c, g("slow")));
    let osc: Vec<f64> = f.iter().zip(&s).map(|(a, b)| a - b).collect();
    let sig = sma(&osc, g("sig"));
    let long_only = p.get("side").copied().unwrap_or(0.) >= 1.;
    let mut tgt = vec![0i8; x.c.len()];
    for i in 1..x.c.len() {
        tgt[i] = if osc[i] > sig[i] && osc[i - 1] <= sig[i - 1] { 1 }
            else if osc[i] < sig[i] && osc[i - 1] >= sig[i - 1] { if long_only { 0 } else { -1 } }
            else { tgt[i - 1] };
    }
    Some(target_trades(x, &tgt, from, to, true, "oscillator crossed its average"))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::Row;
    #[test]
    fn crosses_reverse_at_the_next_open() {
        let c: Vec<f64> = (0..80).map(|i| if i < 40 { 100. - i as f64 * 0.5 } else { 80. + (i - 40) as f64 }).collect();
        let r: Vec<Row> = c.iter().enumerate().map(|(i, &v)| Row { ticker: "T".into(), date: format!("2001-{:02}-{:02}", 1 + i / 28, 1 + i % 28), open: v, high: v + 1., low: v - 1., close: v, volume: None }).collect();
        let x = Ctx::new(&r, &r, &[]);
        let p: Params = [("fast".to_string(), 3.), ("slow".to_string(), 6.), ("sig".to_string(), 3.)].into_iter().collect();
        let t = run("gmtot_trend", &x, 0, r.len() - 1, &p).unwrap();
        assert!(!t.is_empty() && t.iter().all(|z| z.entry_kind == "open"));
        assert_eq!(t.last().unwrap().dir, 1.);
        assert!(run("gmtot_x", &x, 0, 10, &p).is_none());
    }
}

