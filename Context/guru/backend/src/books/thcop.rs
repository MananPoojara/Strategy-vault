pub fn params(id: &str) -> Option<Vec<ParamDef>> {
    let p = |key, label, def, min, max, step| ParamDef { key, label, def, min, max, step };
    reviewed(id).then(|| vec![p("lo", "Buy zone: guide below this, then rising (1.3)", 1.3, -20., 20., 0.1),
        p("drop", "Sell: points below the top (11)", 11., 1., 40., 0.5),
        p("open", "Fills: 0 = signal month's close (default), 1 = next trading day's open", 0., 0., 1., 1.)])
}

pub fn run(id: &str, x: &Ctx, from: usize, to: usize, p: &Params) -> Option<Vec<Trade>> {
    if !reviewed(id) || from >= to || to >= x.r.len() { return None; }
    let schema = params(id)?;
    let g = |k: &str| p.get(k).copied().unwrap_or_else(|| schema.iter().find(|d| d.key == k).unwrap().def);
    let (lo, drop, nxt) = (g("lo"), g("drop"), g("open") > 0.5);
    let mo = crate::books::mpts::period_ends(x, true);
    let idx: Vec<usize> = (0..x.c.len()).filter(|&i| mo[i]).collect();
    let gd = crate::books::mptae::coppock_curve(&idx.iter().map(|&i| x.c[i]).collect::<Vec<_>>());
    let fill = |i: usize| if nxt { (i + 1, x.o[i + 1]) } else { (i, x.c[i]) };
    let kind = if nxt { "open" } else { "close" };
    let (mut out, mut cur) = (vec![], None::<(usize, f64, f64)>); // entry bar, entry price, top since the guide rose above lo
    for k in 1..idx.len() {
        let i = idx[k];
        if i < from || i > to || (nxt && i >= to) { continue; }
        if !(gd[k].is_finite() && gd[k - 1].is_finite()) { continue; }
        if let Some((e, ep, top)) = cur.as_mut() {
            if gd[k] > lo { *top = top.max(gd[k]); }
            if top.is_finite() && gd[k] <= *top - drop {
                let (xi, xp) = fill(i);
                out.push(mk(1., *e, *ep, kind, xi, xp, "guide fell 11 points from its top", false, i));
                cur = None;
            }
            continue;
        }
        if gd[k - 1] < lo && gd[k] > gd[k - 1] {
            let (ei, ep) = fill(i);
            cur = Some((ei, ep, if gd[k] > lo { gd[k] } else { f64::NAN }));
        }
    }
    if let Some((e, ep, _)) = cur { out.push(mk(1., e, ep, kind, to, x.c[to], "open", true, to)); }
    Some(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::Row;
    #[test]
    fn buys_the_upturn_below_1_3_and_sells_11_points_off_the_top() {
        // ~30 years of 21-day months with a 6-year price cycle: the guide swings far beyond 1.3 and 11 points
        let r: Vec<Row> = (0..7560).map(|k| { let f = k as f64; let c = 1000. * (1. + 0.4 * (f / 240.).sin()) + 0.05 * f;
            Row { ticker: "T".into(), date: format!("{:04}-{:02}-{:02}", 1960 + k / 252, 1 + k % 252 / 21, 1 + k % 21), open: c - 1., high: c + 2., low: c - 2., close: c, volume: None } }).collect();
        let x = Ctx::new(&r, &r, &[]);
        let t = run("thcop_guide", &x, 0, r.len() - 1, &Params::new()).unwrap();
        assert!(t.len() >= 4 && t.iter().all(|z| z.dir > 0.));
        for z in &t { assert_eq!(z.legs[0].px, x.c[z.legs[0].i]); assert!(r[z.legs[0].i + 1].date[..7] != r[z.legs[0].i].date[..7]); }
        for w in t.windows(2) { assert!(w[1].legs[0].i > w[0].exit_i); }
        let n = run("thcop_guide", &x, 0, r.len() - 1, &Params::from([("open".to_string(), 1.)])).unwrap();
        for z in &n { assert_eq!(z.legs[0].px, x.o[z.legs[0].i]); }
        assert!(run("thcop_x", &x, 0, 5, &Params::new()).is_none());
    }
}

