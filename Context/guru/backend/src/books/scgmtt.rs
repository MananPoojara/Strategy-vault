pub const REVIEWED: &[&str] = &["scgmtt_tot"];
pub fn reviewed(id: &str) -> bool { REVIEWED.contains(&id) }

const NOTE: &str = "[Adapted: 2 unstated details, R4 #297; unverified] For the DJIA (short-term cycle 14 to 15 days): oscillator = EMA(7) - EMA(42) of the close (the short EMA is half the short-term cycle, the long one six times the short: 'half-dozening'); signal = the 21-day simple average of the oscillator (three times the short EMA); 'Buy and sell signals are generated by using an arithmetic moving average on this oscillator': buy when the oscillator crosses above its average, sell when it crosses below. EMAs: alpha 2/(n+1), seeded with the first close; crossings count once all three averages exist (from bar 42 + 21). Unstated in the article: (1) the fill - vault reading: the close of the signal day; (2) what a sell does - vault reading: closes the long (the article's own example is the untradable DJIA and it speaks of buy and sell signals; option short = 1 also sells short, always in). The optional trading band (a percentage band around the 21-day average 'that will encompass 90 to 95% of the data', with signals best near its limits) is left out: its percentage and its use are not fixed. The article prints two DJIA charts only, no trade table. Runs on indices, ETFs and stocks, US and India, are a declared application (the article: 'the parameters are going to be different for each market').";

