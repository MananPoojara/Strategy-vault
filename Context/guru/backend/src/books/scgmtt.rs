pub fn family_of(id: &str) -> Option<(&'static str, &'static str, &'static str)> { reviewed(id).then_some(("scgmtt_tot", "Morris trend of the trend (S&C)", "7/42/21")) }
pub fn params(id: &str) -> Option<Vec<ParamDef>> {
    reviewed(id).then(|| vec![
        ParamDef { key: "short_ema", label: "Short EMA days = half the short-term cycle (article, DJIA: 7); long EMA = 6x, signal SMA = 3x", def: 7., min: 2., max: 40., step: 1. },
        ParamDef { key: "short", label: "1 = sell short on the sell signal (always in); 0 = long or flat (vault reading)", def: 0., min: 0., max: 1., step: 1. }])
}

pub fn run(id: &str, x: &Ctx, from: usize, to: usize, p: &Params) -> Option<Vec<Trade>> {
    if !reviewed(id) || from > to || to >= x.r.len() { return None; }
    let k = p.get("short_ema").copied().unwrap_or(7.).round().max(1.) as usize;
    let (a, b) = (ema0(&x.c, k), ema0(&x.c, 6 * k));
    let mut osc: Vec<f64> = a.iter().zip(&b).map(|(u, v)| u - v).collect();
    for v in osc.iter_mut().take(6 * k - 1) { *v = f64::NAN; } // the long EMA exists from its 6k-th close
    let s = sma(&osc, 3 * k);
    let dn = if p.get("short").copied().unwrap_or(0.) > 0.5 { -1. } else { 0. };
    Some(at_close(x, from, to, "oscillator crossed below its average", |t, side| {
        if t == 0 || !s[t - 1].is_finite() { return side; }
        if gt(osc[t], s[t]) && !gt(osc[t - 1], s[t - 1]) { 1. } else if gt(s[t], osc[t]) && !gt(s[t - 1], osc[t - 1]) { dn } else { side }
    }))
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn oscillator_crossings_at_the_close() {
        let r = super::super::sctraub::tests::bars(1500);
        let x = Ctx::new(&r, &r, &[]);
        let t = run("scgmtt_tot", &x, 0, r.len() - 1, &Params::new()).unwrap();
        assert!(t.len() > 5 && t.iter().all(|z| z.dir > 0. && z.legs[0].i >= 62 && z.legs[0].px == x.c[z.legs[0].i]));
        assert!(run("scgmtt_tot", &x, 0, r.len() - 1, &Params::from([("short".into(), 1.)])).unwrap().iter().any(|z| z.dir < 0.));
    }
}
