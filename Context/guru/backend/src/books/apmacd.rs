//! Gerald Appel, "Construction & Application of the MACD Indicator" (TAG XVIII, New Orleans 1996,
//! Signalert workshop booklet, 47 pp.). Page refs are the booklet's printed numbers.
//! Uses the MACD engine of the Technical Analysis module (apta). Sources and checks: library/apmacd/.
