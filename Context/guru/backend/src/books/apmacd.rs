pub fn family_of(id: &str) -> Option<(&'static str, &'static str, &'static str)> {
    Some(match id {
        "apmacd_neutral" => ("apmacd_rules", "Appel MACD procedures (1996)", "Neutral/rising trend · 13-26 buy, 19-39 sell"),
        "apmacd_uptrend" => ("apmacd_rules", "Appel MACD procedures (1996)", "Strong uptrend · 6-19 buy, 19-39 sell"),
        "apmacd_downtrend" => ("apmacd_rules", "Appel MACD procedures (1996)", "Declining trend · 13-26 buy and sell"),
        "apmacd_judgement" | "apmacd_intraday" => ("apmacd_rules", "Appel MACD procedures (1996)", ""),
        "apmacd_ad_stay" => ("apmacd_ad", "A-D line MACD stay-in", "NYSE breadth"),
        "apmacd_ad_stay_nse" => ("apmacd_ad", "A-D line MACD stay-in", "NSE breadth"),
        _ => return None,
    })
}

pub fn params(id: &str) -> Option<Vec<ParamDef>> {
    let p = |key, label, def, min, max, step| ParamDef { key, label, def, min, max, step };
    let m = |bf, bs, bsig| vec![p("bf", "Buy MACD fast EMA", bf, 6., 13., 1.), p("bs", "Buy MACD slow EMA", bs, 19., 26., 1.), p("bsig", "Buy signal line EMA", bsig, 6., 9., 1.),
        p("sf", "Sell MACD fast EMA", 19., 13., 19., 1.), p("ss", "Sell MACD slow EMA", 39., 26., 39., 1.), p("ssig", "Sell signal line EMA", 9., 6., 9., 1.),
        p("stop", "MACD stop (1 on, 0 off)", 1., 0., 1., 1.), p("tf", "Bars: 0 daily, 1 weekly, 2 monthly", 0., 0., 2., 1.)];
    Some(match id {
        "apmacd_neutral" | "apmacd_downtrend" => m(13., 26., 9.),
        "apmacd_uptrend" => m(6., 19., 6.),
        "apmacd_ad_stay" | "apmacd_ad_stay_nse" => vec![p("fast", "MACD fast EMA", 19., 10., 26., 1.), p("slow", "MACD slow EMA", 39., 26., 52., 1.), p("level", "Stay in while MACD above", 450., 0., 1000., 50.)],
        _ => return None,
    })
}

pub fn run(id: &str, x: &Ctx, from: usize, to: usize, p: &Params) -> Option<Vec<Trade>> {
    let schema = params(id)?;
    if from > to || to >= x.r.len() {
        return None;
    }
    let g = |k: &str| p.get(k).copied().unwrap_or_else(|| schema.iter().find(|d| d.key == k).unwrap().def);
    let u = |k: &str| g(k).round().max(1.0) as usize;
    Some(match id {
        "apmacd_neutral" | "apmacd_uptrend" | "apmacd_downtrend" => macd_run(x, from, to, &Macd {
            buy: (u("bf"), u("bs"), u("bsig")), sell: (u("sf"), u("ss"), u("ssig")),
            both_above: true, sell_on_buy: id == "apmacd_downtrend", stop: g("stop") > 0.5, tf: g("tf").round().clamp(0., 2.) as u8,
        }),
        "apmacd_ad_stay" | "apmacd_ad_stay_nse" => {
            let pre = if id.ends_with("_nse") { "NSE_ADV_DEC" } else { "NYSE_ADV_DEC" };
            let (Some(a), Some(d)) = (x.series(&format!("{pre}.Advances")), x.series(&format!("{pre}.Declines"))) else { return Some(vec![]) };
            // cumulative A-D line; NaN before the first breadth day, flat on days without data
            let last = (0..a.len()).rev().find(|&i| (a[i] - d[i]).is_finite()).unwrap_or(0);
            let mut lvl = f64::NAN;
            let line: Vec<f64> = (0..a.len()).map(|i| {
                if i > last {
                    return f64::NAN; // after the last breadth day: no data, no signals
                }
                if (a[i] - d[i]).is_finite() {
                    lvl = if lvl.is_finite() { lvl } else { 0.0 } + a[i] - d[i];
                }
                lvl
            }).collect();
            let (f, s) = (ema(&line, u("fast")), ema(&line, u("slow")));
            let lv = g("level");
            let daily: Vec<usize> = (0..x.r.len()).collect();
            run_long(x, &daily, from, to, |_, i, h| {
                let m = f[i] - s[i];
                if !m.is_finite() {
                    None
                } else if !h && m > lv {
                    Some("A-D line MACD above the stay-in level".into())
                } else if h && m <= lv {
                    Some("A-D line MACD at or below the stay-in level".into())
                } else {
                    None
                }
            })
        }
        _ => return None,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn rule_sets_differ_only_in_the_documented_switches() {
        let cat = catalogue();
        assert_eq!(cat.iter().filter(|d| d.status == Status::Live).count(), 5);
        assert_eq!(params("apmacd_uptrend").unwrap()[0].def, 6.0);
        assert_eq!(params("apmacd_neutral").unwrap()[0].def, 13.0);
    }
}
