/// 41 x the improved price-analysis estimate at weekly close k (p.104): the 41-week total, less the total of its oldest
/// 10 closes, plus 10 x the latest close. Needs k >= 40.
pub fn estimate_total(wc: &[f64], k: usize) -> f64 {
    let t41: f64 = wc[k - 40..=k].iter().sum();
    let t10: f64 = wc[k - 40..k - 30].iter().sum();
    t41 - t10 + 10. * wc[k]
}

pub fn run(id: &str, x: &Ctx, from: usize, to: usize, p: &Params) -> Option<Vec<Trade>> {
    if !reviewed(id) || from >= to || to >= x.r.len() { return None; }
    let schema = params(id)?;
    let g = |k: &str| p.get(k).copied().unwrap_or_else(|| schema.iter().find(|d| d.key == k).map_or(f64::NAN, |d| d.def));
    let (limit, floor) = (g("limit").round().max(0.) as usize, 1. - g("stop") / 100.);
    let c = &x.c;
    let we: Vec<usize> = week_ends(x).into_iter().filter(|&i| i <= to).collect();
    let wc: Vec<f64> = we.iter().map(|&i| c[i]).collect();
    let est: Vec<f64> = (0..wc.len()).map(|k| if k >= 40 { estimate_total(&wc, k) } else { f64::NAN }).collect();
    let mk = |e: usize, xi: usize, why: &str, open: bool| Trade { dir: 1., legs: vec![Leg { i: e, px: c[e], w: 1. }],
        exit_i: xi, exit_px: c[xi], reason: why.into(), entry_kind: "close", signal_i: xi, open, exits: vec![] };
    let (mut out, mut cur) = (vec![], None::<(usize, usize, f64)>); // (entry week, entry bar, highest weekly close)
    for k in 0..wc.len() {
        let i = we[k];
        if let Some((k0, e, peak)) = cur {
            let why = if wc[k] < peak * floor { Some("stop-loss floor") } else if limit > 0 && k - k0 >= limit { Some("time limit") } else { None };
            cur = match why { Some(w) => { out.push(mk(e, i, w, false)); None } None => Some((k0, e, peak.max(wc[k]))) };
        }
        if cur.is_none() && k >= 41 && i >= from && i < to
            && wc[k] > wc[k - 5] && wc[k - 1] <= wc[k - 6] // five-week average turns up (drop-point, p.146)
            && wc[k] > wc[k - 1] && wc[k] > wc[k - 3] && est[k] > est[k - 1] {
            cur = Some((k, i, wc[k]));
        }
    }
    if let Some((_, e, _)) = cur { out.push(mk(e, to, "open", true)); }
    Some(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::Row;
    // FTSE 100 weekly closes 16/07/93 - 23/06/94 (Table 7.5, p.105). 24/06/94 is 2876.6 as in Table 5.2 (p.61); the
    // OCR of Table 7.5 reads 2876.7, but only 2876.6 gives the table's own totals 130736.8 / 128560.6.
    const FTSE: [f64; 50] = [2833.0, 2827.7, 2926.5, 2969.8, 3010.1, 3057.6, 3100.6, 3057.3, 3037.0, 3005.5, 3005.2, 3039.3, 3108.6, 3120.8,
        3199.0, 3171.0, 3085.6, 3099.1, 3108.1, 3111.4, 3234.2, 3261.3, 3337.1, 3412.3, 3418.4, 3446.0, 3400.6, 3484.2, 3447.4, 3475.4,
        3378.9, 3382.6, 3281.2, 3278.0, 3191.9, 3218.1, 3129.0, 3086.4, 3120.8, 3168.3, 3133.7, 3125.3, 3106.0, 3119.2, 3127.3, 2966.4,
        2997.8, 3055.9, 3022.9, 2876.6];
    #[test]
    fn rebuilds_the_book_ftse_estimate() {
        // 22/04/94: 130159.0 - 29825.1 + 10 x 3133.7 = 131670.9, / 41 = 3211.49 (p.104); then Table 7.5's column to 24/06/94
        let book = [131670.9, 131707.0, 131580.7, 131723.3, 131810.8, 129969.2, 130110.0, 130661.3, 130255.1, 128560.6];
        for (j, &b) in book.iter().enumerate() {
            assert!((estimate_total(&FTSE, 40 + j) - b).abs() < 0.05, "week {} {} vs {b}", 40 + j, estimate_total(&FTSE, 40 + j));
        }
        assert!(((estimate_total(&FTSE, 40) / 41. * 100.).round() - 321149.).abs() < 0.5);
    }
    fn weekly(cl: &[f64]) -> Vec<Row> {
        // one bar per week, each a Friday (1999-01-01 was a Friday)
        cl.iter().enumerate().map(|(k, &v)| {
            let z = 10592 + 7 * k as i64 + 719468; let era = z.div_euclid(146097); let doe = z - era * 146097;
            let yoe = (doe - doe / 1460 + doe / 36524 - doe / 146096) / 365; let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
            let mp = (5 * doy + 2) / 153; let d = doy - (153 * mp + 2) / 5 + 1; let m = if mp < 10 { mp + 3 } else { mp - 9 };
            Row { ticker: "T".into(), date: format!("{}-{:02}-{:02}", yoe + era * 400 + if m <= 2 { 1 } else { 0 }, m, d), open: v, high: v, low: v, close: v, volume: None }
        }).collect()
    }
    #[test]
    fn hand_checked_turn_floor_and_time_limit() {
        // 40 weeks rising 100..139 (k = 0..39), then falling closes k = 40..44 (no buy on a fall), then 140 at k = 45
        let mut cl: Vec<f64> = (0..40).map(|k| 100. + k as f64).collect();
        cl.extend([139., 137., 135., 134., 133., 140.]); // k = 45: 140 > wc[40] = 139, wc[44] = 133 <= wc[39] = 139: turn; 140 > 133, > 135
        cl.extend([141., 142., 129.]); // k = 48: 129 < 0.925 x 142 = 131.35 -> floor
        let r = weekly(&cl);
        let x = Ctx::new(&r, &r, &[]);
        let t = run("bmwsm_5wk_turn", &x, 0, r.len() - 1, &Params::new()).unwrap();
        let got: Vec<_> = t.iter().map(|z| (z.legs[0].i, z.legs[0].px, z.exit_i, z.exit_px, z.reason.as_str(), z.open)).collect();
        assert_eq!(got, vec![(45, 140., 48, 129., "stop-loss floor", false)]);
        // same entry, then 21 flat weeks: out at the close 20 weeks after purchase; with limit 0 still open at the end
        let mut cl2: Vec<f64> = cl[..46].to_vec();
        cl2.extend([140.; 21]);
        let r2 = weekly(&cl2);
        let x2 = Ctx::new(&r2, &r2, &[]);
        let t2 = run("bmwsm_5wk_turn", &x2, 0, r2.len() - 1, &Params::new()).unwrap();
        assert_eq!((t2[0].legs[0].i, t2[0].exit_i, t2[0].reason.as_str()), (45, 65, "time limit"));
        let p0: Params = [("limit".to_string(), 0.)].into_iter().collect();
        let t3 = run("bmwsm_5wk_turn", &x2, 0, r2.len() - 1, &p0).unwrap();
        assert_eq!((t3.len(), t3[0].exit_i, t3[0].open), (1, 66, true));
        assert!(run("bmwsm_x", &x, 0, r.len() - 1, &Params::new()).is_none());
    }
}

